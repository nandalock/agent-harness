"""Generate the TypeScript RPC contract from controller Pydantic models.

Run from the repository root:
    python scripts/generate_rpc_contracts.py

The output is committed and checked by tests; controllers remain the single
source of truth for request/response shapes.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from agent_platform_api_agents import METHODS as AGENT_METHODS
from agent_platform_api_sessions import METHODS as SESSION_METHODS
from agent_platform_api_workspace import METHODS as WORKSPACE_METHODS

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "packages" / "client" / "legacy" / "lib" / "remote" / "contracts.generated.ts"

METHODS = (*WORKSPACE_METHODS, *AGENT_METHODS, *SESSION_METHODS)


def _ts_type(schema: dict[str, Any], indent: str = "  ") -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        parts = [_ts_type(item, indent) for item in schema["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{_ts_type(schema.get('items', {}), indent)}>"
    if kind == "object":
        props = schema.get("properties")
        if props is None:
            return "Record<string, unknown>"
        required = set(schema.get("required") or ())
        lines = ["{"]
        for name, prop in props.items():
            optional = "" if name in required else "?"
            lines.append(f"{indent}{name}{optional}: {_ts_type(prop, indent + '  ')};")
        lines.append(indent[:-2] + "}")
        return "\n".join(lines)
    return "unknown"


def _collect_defs(schema: dict[str, Any], found: dict[str, dict[str, Any]]) -> None:
    for name, definition in (schema.get("$defs") or {}).items():
        found.setdefault(name, definition)
        _collect_defs(definition, found)


def _render_named(schema: dict[str, Any], name: str) -> str:
    required = set(schema.get("required") or ())
    lines = [f"export interface {name} {{"]
    for field, prop in (schema.get("properties") or {}).items():
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_ts_type(prop)};")
    lines.append("}")
    return "\n".join(lines)


def render_contracts() -> str:
    interfaces: dict[str, str] = {}
    all_defs: dict[str, dict[str, Any]] = {}
    method_rows: list[str] = []
    for contract in METHODS:
        params_schema = contract.params_model.model_json_schema()
        _collect_defs(params_schema, all_defs)
        params_name = contract.params_model.__name__
        interfaces[params_name] = _render_named(params_schema, params_name)
        if contract.result_model is not None:
            result_schema = contract.result_model.model_json_schema()
            _collect_defs(result_schema, all_defs)
            result_name = contract.result_model.__name__
            interfaces[result_name] = _render_named(result_schema, result_name)
        else:
            result_name = "unknown"
        method_rows.append(
            f'  {json.dumps(contract.method)}: {{ params: {params_name}; result: {result_name} }};'
        )
    for name, schema in all_defs.items():
        if name not in interfaces:
            interfaces[name] = _render_named(schema, name)
    lines = [
        "// Generated by scripts/generate_rpc_contracts.py. Do not edit by hand.",
        "/* eslint-disable */",
        "",
    ]
    for name in sorted(interfaces):
        lines.append(interfaces[name])
        lines.append("")
    lines.append("export interface RpcMethods {")
    lines.extend(method_rows)
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = render_contracts()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
